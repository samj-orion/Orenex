export type SourceKind = 'geology' | 'geophysics' | 'satellite' | 'weather' | 'operations' | 'drilling' | 'derived' | 'simulated';
export type QualityStatus = 'ok' | 'stale' | 'degraded' | 'quarantined';

export interface DataSource {
  id: string;
  name: string;
  provider: string;
  kind: SourceKind;
  connector: string;
  schedule: string;
  lastRun: string;
  nextRun: string;
  /** Fraction of the AOI with usable data. */
  coveragePct: number;
  rowsLanded: number;
  quality: QualityStatus;
  validationPassPct: number;
  crs: string;
  licence: string;
  synthetic: boolean;
  checksum: string;
  /** Dependent services, so a stale source can mark them reduced-confidence. */
  consumers: string[];
  notes: string;
}

